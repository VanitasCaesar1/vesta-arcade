// Vendors Geist (SIL OFL 1.1) and a few Phosphor icons (MIT) into the Worker
// as plain TS modules, so the arcade needs no font CDN and no asset bucket.
// Run after upgrading either package: node scripts/vendor-assets.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { existsSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

// Workspaces hoist packages to the repo root; look there and next to the worker.
const pkg = (name) => {
  for (const base of ["../node_modules", "../../node_modules"]) {
    const dir = fileURLToPath(new URL(`${base}/${name}`, import.meta.url));
    if (existsSync(dir)) return dir;
  }
  throw new Error(`${name} is not installed. Run npm install.`);
};
const geist = pkg("geist");
const phosphor = pkg("@phosphor-icons/core");
const archivo = pkg("@fontsource-variable/archivo");

const font = (p) => readFileSync(join(geist, "dist/fonts", p)).toString("base64");
writeFileSync(
  new URL("../src/site/fonts.ts", import.meta.url),
  `// Generated by scripts/vendor-assets.mjs. Geist and Geist Mono, SIL Open Font License 1.1 (https://github.com/vercel/geist-font).\n` +
    `export const GEIST = "${font("geist-sans/Geist-Variable.woff2")}";\n` +
    `export const GEIST_MONO = "${font("geist-mono/GeistMono-Variable.woff2")}";\n` +
    `// Archivo (width and weight axes), SIL Open Font License 1.1 (https://github.com/Omnibus-Type/Archivo).\n` +
    `export const ARCHIVO = "${readFileSync(join(archivo, "files/archivo-latin-wdth-normal.woff2")).toString("base64")}";\n`,
);

const ICONS = {
  play: "fill/play-fill",
  heart: "regular/heart",
  heartFill: "fill/heart-fill",
  share: "regular/share-network",
  expand: "regular/arrows-out",
  code: "regular/code",
  keyboard: "regular/keyboard",
  github: "regular/github-logo",
  terminal: "regular/terminal-window",
  arrowRight: "regular/arrow-right",
  arrowUpRight: "regular/arrow-up-right",
  copy: "regular/copy",
  shuffle: "regular/shuffle",
  bug: "regular/bug",
  chat: "regular/chat-circle",
  history: "regular/clock-counter-clockwise",
  controller: "regular/game-controller",
};
const out = Object.entries(ICONS).map(([name, path]) => {
  const svg = readFileSync(join(phosphor, "assets", `${path}.svg`), "utf8")
    .replace(/<svg [^>]*>/, '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 256 256" fill="currentColor" aria-hidden="true">')
    .replace(/\s+/g, " ")
    .trim();
  return `  ${name}: ${JSON.stringify(svg)},`;
});
writeFileSync(
  new URL("../src/site/icons.ts", import.meta.url),
  `// Generated by scripts/vendor-assets.mjs. Phosphor Icons, MIT (https://phosphoricons.com).\nexport const ICONS = {\n${out.join("\n")}\n} as const;\n`,
);
console.log("Vendored Geist and", Object.keys(ICONS).length, "Phosphor icons");
